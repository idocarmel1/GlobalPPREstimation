"""Assemble the Excel deliverable from the CSVs the pipeline has already written.

Derived cells (medians, ranges, spreads, system totals) are written as **formulas** rather
than as Python-computed literals, so the workbook recalculates if anyone edits an input
and a reader can see exactly how each figure was produced.

The benthic sheet is included only when ``benthic.enabled`` and the CSV exists, and it
carries its own provenance block. Nothing on the main sheets depends on it.
"""

