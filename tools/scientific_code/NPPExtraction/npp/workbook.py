def _summary(wb, cfg: Config, ens: pd.DataFrame, n_rows: int) -> None:
    models = list(cfg.ensemble.models)
    ws = wb.create_sheet("Summary")
    ws["A1"] = f"System totals, {cfg.year}"
    ws["A1"].font = TITLE
    ws["A2"] = "Pg C per year. Every value is a formula over the Ensemble sheet."
    ws["A2"].font = SUBTLE
    cols = ["System", "Regions", "Water area (M km2)"] + [MODEL_LABELS[m] for m in models] + \
           ["Ensemble median", "Ensemble min", "Ensemble max", "Spread (% of median)"]
    r0 = 4
    for j, h in enumerate(cols, 1):
        c = ws.cell(r0, j, h)
        c.font, c.fill = HEAD, HFILL
        c.alignment = Alignment(wrap_text=True, horizontal="left" if j == 1 else "right")
    last = n_rows + 1
    first_model_col = 4
    nm = len(models)
    med_col = get_column_letter(first_model_col + nm)
    systems = [(lay, lab) for lay, lab in
               (("lme", "LME"), ("highseas", "HighSeas"), ("eez", "EEZ")) if lay in cfg.layers]
    for k, (lay, tag) in enumerate(systems):
        i = r0 + 1 + k
        ws.cell(i, 1, f"{tag}")
        ws.cell(i, 2, f'=COUNTIF(Ensemble!$A$2:$A${last},"{tag}")')
        ws.cell(i, 3, f'=SUMIF(Ensemble!$A$2:$A${last},"{tag}",Ensemble!$D$2:$D${last})/1000')
        for j, m in enumerate(models):
            cl = get_column_letter(5 + j)          # model columns start at E on Ensemble
            ws.cell(i, first_model_col + j,
                    f'=SUMIF(Ensemble!$A$2:$A${last},"{tag}",Ensemble!${cl}$2:${cl}${last})/1000000000')
        a = get_column_letter(first_model_col)
        b = get_column_letter(first_model_col + nm - 1)
        ws.cell(i, first_model_col + nm, f"=MEDIAN({a}{i}:{b}{i})")
        ws.cell(i, first_model_col + nm + 1, f"=MIN({a}{i}:{b}{i})")
        ws.cell(i, first_model_col + nm + 2, f"=MAX({a}{i}:{b}{i})")
        ws.cell(i, first_model_col + nm + 3,
                f'=IFERROR(({get_column_letter(first_model_col+nm+2)}{i}'
                f'-{get_column_letter(first_model_col+nm+1)}{i})/{med_col}{i}*100,"")')
        for j in range(1, len(cols) + 1):
            c = ws.cell(i, j)
            c.font, c.border = BODY, EDGE
            c.number_format = INT if j == 2 else (ONE if j in (3, len(cols)) else TWO)
    i = r0 + 1 + len(systems) + 1
    ws.cell(i, 1, "Median per-region spread (%)").font = SUBTLE
    for k, (lay, _tag) in enumerate(systems):
        v = float(ens[ens.layer == lay].spread_pct.median())
        c = ws.cell(i, first_model_col + k, v)
        c.font, c.number_format = SUBTLE, ONE
    notes = [
        "",
        'The "Spread" column on the system rows is the spread of the five SYSTEM TOTALS. The spread that applies',
        "to a single region is much larger - see the row of medians above and the per-region column on Ensemble.",
        "The median per-region spread is computed by the build script, not by a cell formula (Excel cannot take a",
        "conditional median without an array formula, which openpyxl cannot mark as one).",
        "",
        "The system rows must NOT be added together: the region systems overlap. See the Overlap sheet.",
    ]
    for k, t in enumerate(notes):
        ws.cell(i + 2 + k, 1, t).font = NOTE
    ws.column_dimensions["A"].width = 34
    for j in range(2, len(cols) + 1):
        ws.column_dimensions[get_column_letter(j)].width = 15
    ws.sheet_view.showGridLines = False


def build_workbook(cfg: Config) -> Path:
    models = list(cfg.ensemble.models)
    out_dir = Path(cfg.out_dir)
    base = pd.read_csv(out_dir / f"npp_{cfg.year}_baseline_by_region.csv")
    ens = pd.read_csv(out_dir / f"npp_{cfg.year}_ensemble_by_region.csv")
    monthly = pd.read_csv(out_dir / f"npp_{cfg.year}_baseline_monthly.csv")
    ov_path = out_dir / "region_system_overlap.csv"
    ov = pd.read_csv(ov_path) if ov_path.exists() else None
    ben_path = out_dir / f"benthic_{cfg.year}_by_LME_firstorder.csv"
    ben = pd.read_csv(ben_path) if (cfg.benthic.enabled and ben_path.exists()) else None

    wb = Workbook()
    wb.remove(wb.active)
    _readme(wb, cfg, base, ens)

    # ---------------------------------------------------------------- Ensemble
    labels = [MODEL_LABELS[m] for m in models]
    hdr = (["System", "Region ID", "Region", "Water area (1000 km2)"]
           + [f"{l} (tC/yr)" for l in labels]
           + ["Ensemble median (tC/yr)", "Ensemble min (tC/yr)", "Ensemble max (tC/yr)",
              "Spread (% of median)", "CV (%)", "Median rate (mgC/m2/d)",
              "Models used", "Ensemble basis", "Common mask (% of water)",
              "SAU published PP (mgC/m2/d)", "Ours / SAU"])
    sau = dict(zip(zip(base.layer, base.region_id), base.get("sau_pp_mgC_m2_d", pd.Series(dtype=float))))
    rows = []
    for _, x in ens.iterrows():
        rows.append([x.system, int(x.region_id), x.title, x.water_area_km2 / 1e3]
                    + [x[f"scaled_{m}_tC_yr"] for m in models]
                    + [None] * 6
                    + [int(x.n_models), x.ensemble_basis, x.common_area_pct_of_water,
                       sau.get((x.layer, int(x.region_id))), None])
    nm = len(models)
    first, last_model = 5, 4 + nm
    fmts = {4: ONE, **{k: INT for k in range(first, last_model + 4)},
            last_model + 4: PCT, last_model + 5: PCT, last_model + 6: ONE,
            last_model + 7: INT, last_model + 10: PCT, last_model + 11: ONE, last_model + 12: TWO}
    widths = [11, 10, 34, 14] + [15] * nm + [16, 15, 15, 12, 9, 14, 9, 15, 15, 15, 10]
    ws = _sheet(wb, "Ensemble", hdr, rows, widths=widths, fmts=fmts, notes=[
        "Median / min / max / spread / CV / rate / ratio are formulas over the model columns of each row.",
        "Model columns are the ensemble carried onto the gap-filled baseline, so they are absolute and complete.",
        "A blank model cell means that algorithm has no data for that region - check 'Models used'.",
    ])
    A, B = get_column_letter(first), get_column_letter(last_model)
    for i in range(2, len(rows) + 2):
        med = get_column_letter(last_model + 1)
        mn = get_column_letter(last_model + 2)
        mx = get_column_letter(last_model + 3)
        ws.cell(i, last_model + 1, f"=MEDIAN({A}{i}:{B}{i})")
        ws.cell(i, last_model + 2, f"=MIN({A}{i}:{B}{i})")
        ws.cell(i, last_model + 3, f"=MAX({A}{i}:{B}{i})")
        ws.cell(i, last_model + 4, f'=IFERROR(({mx}{i}-{mn}{i})/{med}{i}*100,"")')
        ws.cell(i, last_model + 5, f'=IFERROR(STDEV({A}{i}:{B}{i})/AVERAGE({A}{i}:{B}{i})*100,"")')
        ws.cell(i, last_model + 6, f'=IFERROR({med}{i}/(D{i}*1000)/365*1000,"")')
        ws.cell(i, last_model + 12,
                f'=IFERROR({get_column_letter(last_model+6)}{i}/{get_column_letter(last_model+11)}{i},"")')
        for j in range(last_model + 1, last_model + 7):
            ws.cell(i, j).font = BODY
        ws.cell(i, last_model + 12).font = BODY
    _summary(wb, cfg, ens, len(rows))

    # ---------------------------------------------------------------- Baseline
    bh = (["System", "Region ID", "Region", "Polygon area (1000 km2)", "Water area (1000 km2)",
           "NPP central (tC/yr)", "NPP observed only (tC/yr)", "NPP no spatial fill (tC/yr)",
           "NPP all fills (tC/yr)", "NPP multi-year mean (tC/yr)", "Fill uplift (%)",
           "Mean rate (mgC/m2/d)"]
          + [f"Area {c} (%)" for c in CATEGORIES] + [f"NPP {c} (%)" for c in CATEGORIES]
          + ["Anomaly factor min", "Anomaly factor max",
             "SAU published PP (mgC/m2/d)", "Ours / SAU"])
    brows = []
    for _, x in base.iterrows():
        brows.append([x.system, int(x.region_id), x.title, x.polygon_area_km2 / 1e3,
                      x.water_area_km2 / 1e3, x.npp_central_tC_yr, x.npp_observed_tC_yr,
                      x.npp_no_nn_tC_yr, x.npp_all_fills_tC_yr, x.npp_mean_year_tC_yr,
                      x.fill_uplift_pct, x.mean_rate_mgC_m2_d]
                     + [x[f"area_{c}_pct"] for c in CATEGORIES]
                     + [x[f"npp_{c}_pct"] for c in CATEGORIES]
                     + [x.anomaly_factor_min, x.anomaly_factor_max,
                        x.get("sau_pp_mgC_m2_d"), x.get("ratio_vs_sau")])
    nc = len(CATEGORIES)
    bf = {4: ONE, 5: ONE, **{k: INT for k in range(6, 11)}, 11: PCT, 12: ONE,
          **{k: PCT for k in range(13, 13 + 2 * nc)},
          13 + 2 * nc: TWO, 14 + 2 * nc: TWO, 15 + 2 * nc: ONE, 16 + 2 * nc: TWO}
    _sheet(wb, "Baseline", bh, brows,
           widths=[11, 10, 34, 14, 14, 15, 16, 16, 15, 16, 10, 13] + [9] * (2 * nc) + [11, 11, 15, 10],
           fmts=bf, notes=[
               "One row per region. 'central' uses the fill stages listed on the README sheet.",
               "'Fill uplift' is central / observed-only - 1: how much the year's gaps were worth.",
               "SAU's published value is a 1998-2007 SeaWiFS climatology at 9 km, so it is a sanity check, not truth.",
           ])

    # ---------------------------------------------------------------- Overlap
    if ov is not None:
        cols = [c for c in ov.columns if c.startswith("pct_also_in_") or c.startswith("km2_also_in_")]
        oh = ["System", "Region ID", "Region", "Area (1000 km2)"] + [
            c.replace("pct_also_in_", "Share also in ").replace("km2_also_in_", "Area also in ")
            .replace("lme", "LME (%)" if c.startswith("pct") else "LME (1000 km2)")
            .replace("highseas", "high seas (%)" if c.startswith("pct") else "high seas (1000 km2)")
            .replace("eez", "an EEZ (%)" if c.startswith("pct") else "an EEZ (1000 km2)")
            for c in cols]
        orows = [[x.system, int(x.region_id), x.title, x.area_km2 / 1e3]
                 + [(x[c] / 1e3 if c.startswith("km2_") else x[c]) for c in cols]
                 for _, x in ov.iterrows()]
        _sheet(wb, "Overlap", oh, orows,
               widths=[11, 10, 34, 14] + [16] * len(cols),
               fmts={4: ONE, **{5 + k: (PCT if c.startswith("pct") else ONE) for k, c in enumerate(cols)}},
               notes=[
                   "Overlap per cell is min(coverage_a, coverage_b) x cell area - exact where one region nests",
                   "inside the other within a cell, which is the normal case for regions this large.",
                   "About half of all EEZ area sits inside an LME; the Arctic Sea high-seas area is ~100% inside",
                   "the Central Arctic Ocean LME. Use EEZ + high seas if you need a disjoint partition.",
               ])

    # ---------------------------------------------------------------- Monthly
    mh = ["System", "Region ID", "Region", "Month", "Days", "NPP central (tC)",
          "NPP observed (tC)", "Rate central (gC/m2/d)"] + [f"Area {c} (%)" for c in CATEGORIES] + \
         ["Anomaly factor"]
    mrows = [[x.system, int(x.region_id), x.title, int(x.month), int(x.days),
              x.npp_central_tC, x.npp_observed_tC, x.rate_central_gC_m2_d]
             + [x[f"area_{c}_pct"] for c in CATEGORIES] + [x.anomaly_factor]
             for _, x in monthly.iterrows()]
    _sheet(wb, "Monthly", mh, mrows,
           widths=[11, 10, 34, 7, 7, 14, 14, 13] + [9] * nc + [11],
           fmts={4: INT, 5: INT, 6: INT, 7: INT, 8: "0.000",
                 **{9 + k: PCT for k in range(nc)}, 9 + nc: TWO})

    # ---------------------------------------------------------------- Benthic (optional)
    if ben is not None:
        habitats = [c[:-3] for c in ben.columns if c.endswith("_tC")
                    and not c.startswith(("benthic", "coral"))
                    and not c.endswith(("_low_tC", "_high_tC", "_available_tC"))]
        bh2 = (["Region ID", "LME", "Mean |lat| (deg)", "Shelf area (1000 km2)", "Light index",
                "Pelagic NPP central (tC/yr)", "Benthic NPP (tC/yr)", "Benthic low (tC/yr)",
                "Benthic high (tC/yr)", "Benthic availability-weighted (tC/yr)",
                "Benthic as % of pelagic", "Availability-weighted (%)"]
               + [f"{h} (tC/yr)" for h in habitats]
               + ["Coral reef GROSS PP (tC/yr) - NOT additive", "Dominant habitat"])
        brows2 = [[int(x.region_id), x.title, x.abs_lat, (x.sau_shelf_km2 or 0) / 1e3, x.light_index,
                   x.npp_central_tC_yr, x.benthic_tC, x.benthic_low_tC, x.benthic_high_tC,
                   x.benthic_available_tC, x.pct_of_pelagic, x.pct_available_of_pelagic]
                  + [x[f"{h}_tC"] for h in habitats]
                  + [x.coral_reef_gross_tC, x.dominant_habitat]
                  for _, x in ben.iterrows()]
        _sheet(wb, "Benthic_LME", bh2, brows2,
               widths=[10, 32, 12, 14, 10, 16, 14, 14, 14, 17, 13, 13] + [15] * len(habitats) + [20, 18],
               fmts={3: ONE, 4: ONE, 5: TWO, **{k: INT for k in range(6, 11)}, 11: PCT, 12: PCT,
                     **{13 + k: INT for k in range(len(habitats))}, 13 + len(habitats): INT},
               notes=[
                   "FIRST-ORDER ESTIMATE, not a measurement. Per-region values are within about a factor of two;",
                   "the global habitat totals are far better constrained than their distribution across regions.",
                   "NONE OF THE MAIN SHEETS INCLUDE THIS. It is an optional add-on, off by default.",
                   "Global totals from the literature, distributed by shelf area / inshore fishing area / SAU coral",
                   "share, each scaled by a light index (insolation at that latitude x the ice-free lit fraction of",
                   "the year). Macroalgae 1.32 Pg C/yr (Duarte et al. 2022, doi 10.1111/geb.13515) is a NICHE MODEL",
                   "and is three quarters of the total. Microphytobenthos ~0.42 Pg C/yr (Cahoon 1999) has no global",
                   "map at all. Mangrove 218+/-72 Tg C/yr (Bouillon et al. 2008). Seagrass ~0.064 Pg C/yr (McKenzie",
                   "et al. 2020). Salt marsh ~0.066 Pg C/yr (Mcowen et al. 2017, 43 countries only).",
                   "Coral reef NET community production is near zero (Gattuso et al. 1998) - the gross column is",
                   "context only and MUST NOT be added to a denominator.",
                   "Availability weighting is the fraction grazed or exported as consumable detritus rather than",
                   "buried or respired in place (Duarte & Cebrian 1996). Classical PPR uses UNWEIGHTED NPP, so do",
                   "not mix conventions: either add raw to raw, or weight both sides.",
                   "See npp/benthic.py for every parameter and citation, and METHODS.md for the fuller discussion.",
               ])

    order = [n for n in ["README", "Summary", "Ensemble", "Baseline", "Overlap", "Monthly", "Benthic_LME"]
             if n in wb.sheetnames]
    wb._sheets = [wb[n] for n in order]
    out = out_dir / f"NPP_{cfg.year}_SAU_regions.xlsx"
    wb.save(out)
    log(f"workbook: -> {out} ({len(order)} sheets)")
    return out
