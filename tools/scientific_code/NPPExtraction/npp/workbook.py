BODY = Font(name="Arial", size=10)
HEAD = Font(name="Arial", size=9, bold=True, color="FFFFFF")
BOLD = Font(name="Arial", size=10, bold=True)
TITLE = Font(name="Arial", size=13, bold=True)
SUBTLE = Font(name="Arial", size=10, italic=True, color="555555")
NOTE = Font(name="Arial", size=9, color="666666")
HFILL = PatternFill("solid", fgColor="0B6F63")
BAND = PatternFill("solid", fgColor="EEF4F3")
EDGE = Border(bottom=Side(style="thin", color="D0DAD9"))
INT, ONE, TWO, PCT = "#,##0", "#,##0.0", "0.00", "0.0"


def _clean(v):
    """NaN must become an empty cell: openpyxl writes float('nan') as a literal that
    LibreOffice and Excel then read as #VALUE!."""
    if v is None:
        return None
    if isinstance(v, str):
        return v
    try:
        f = float(v)
    except (TypeError, ValueError):
        return v
    return None if not np.isfinite(f) else f


def _sheet(wb, name, headers, rows, widths=None, fmts=None, notes=()):
    ws = wb.create_sheet(name)
    for j, h in enumerate(headers, 1):
        c = ws.cell(1, j, h)
        c.font, c.fill = HEAD, HFILL
        c.alignment = Alignment(wrap_text=True, vertical="bottom",
                                horizontal="left" if j <= 4 else "right")
    for i, row in enumerate(rows, 2):
        for j, v in enumerate(row, 1):
            c = ws.cell(i, j, _clean(v))
            c.font, c.border = BODY, EDGE
            if fmts and fmts.get(j):
                c.number_format = fmts[j]
            if i % 2 == 0:
                c.fill = BAND
    ws.freeze_panes = "A2"
    if rows:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows)+1}"
    for j, w in enumerate(widths or [], 1):
        ws.column_dimensions[get_column_letter(j)].width = w
    ws.row_dimensions[1].height = 44
    for k, t in enumerate(notes):
        ws.cell(len(rows) + 3 + k, 1, t).font = NOTE
    return ws


